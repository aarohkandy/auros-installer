// Command gen builds the synthetic corpus the migration installer is tested against, and the golden
// manifest that every later check is measured against.
//
// ─────────────────────────────────────────────────────────────────────────────────────────────────
// DETERMINISM IS THE POINT
// ─────────────────────────────────────────────────────────────────────────────────────────────────
//
// A failure that cannot be reproduced is a story about something that happened once. The whole value of
// this harness is that `gen generate -seed 7 -profile realistic` produces a BYTE-IDENTICAL corpus on
// every machine, forever, so that "run 63 lost a file" can be re-run until it is understood.
//
// Rules this file obeys, and they are not stylistic:
//
//   - No time.Now, anywhere. Not for seeding, not for file mtimes, not in the manifest. The manifest
//     carries no timestamp at all; timestamps belong to a RUN, and runs are the runner's business.
//   - No math/rand. Go has changed math/rand's output for a given seed before and math/rand/v2
//     explicitly refuses to promise stability. We carry our own splitmix64 (16 lines, below) because a
//     PRNG we can read is worth more here than one we have to trust.
//   - No floating point in any decision that selects bytes. Size buckets are integer tables sampled by
//     integer arithmetic. Box-Muller off math.Log would have been prettier and would have made the
//     corpus depend on libm.
//   - A file's CONTENT is a pure function of (seed, relative path, size, extension) via SHA-256 key
//     derivation — not of generation order. So content can be re-derived independently of this program's
//     control flow, and a reordering bug cannot silently change the corpus.
//
// COPY ORDER is defined here too, and it matters: the manifest is sorted by byte order of the
// forward-slash relative path, and `index` is assigned after that sort. The installer under test MUST
// copy in manifest index order. That is what lets fault/ say "kill at 43% of bytes" and resolve it,
// before any VM starts, to an exact (file index, byte offset) that is the same on every re-run.
//
// ─────────────────────────────────────────────────────────────────────────────────────────────────
// WHAT THIS PROGRAM WILL NOT DO
// ─────────────────────────────────────────────────────────────────────────────────────────────────
//
// Spec §4.7 / SAFETY.md rule 3: never test against the operator's own machine. That is enforced here,
// not merely written down. `generate` refuses to write anything unless it is handed a harness token
// (see assertScratchTarget) that the runner mints per suite, that lives on an attached marker volume,
// and that names the exact volume serial of the corpus root. On a real machine the serial does not
// match and the program exits 2 having written nothing. There is no flag that turns this off.
