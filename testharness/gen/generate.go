// Stream is an NTFS alternate data stream. Real school laptops are full of these: every file downloaded
// through a browser carries a Zone.Identifier stream, and a copy tool that silently drops them has
// changed the user's machine in a way that shows up later as "Windows says this file is blocked".
type Stream struct {
	Name   string `json:"name"`
	Size   int64  `json:"size"`
	SHA256 string `json:"sha256"`
}

// FileRec is one line of golden-manifest.jsonl.
type FileRec struct {
	Index   int      `json:"index"` // copy order. Assigned after the canonical sort. The pin anchor.
	Path    string   `json:"path"`  // forward-slash, relative to the corpus root
	WinPath string   `json:"win_path"`
	Size    int64    `json:"size"`
	SHA256  string   `json:"sha256"`
	Cohort  string   `json:"cohort"`
	Attrs   []string `json:"attrs,omitempty"`
	Streams []Stream `json:"streams,omitempty"`

	// Placeholder marks a file we have made LOOK like a OneDrive Files-On-Demand placeholder.
	// PlaceholderFidelity says how honestly. See applyPlaceholder for why this distinction exists and
	// why it must never be dropped from the manifest.
	Placeholder         bool   `json:"placeholder,omitempty"`
	PlaceholderFidelity string `json:"placeholder_fidelity,omitempty"`

	// LockedAtRuntime files are not locked by this program — it exits, and a process that has exited
	// holds no handles. The runner starts `gen hold` as a separate long-lived process before the
	// installer runs. This flag is the contract between the two.
	LockedAtRuntime bool `json:"locked_at_runtime,omitempty"`

	WinPathLen       int  `json:"win_path_len"`
	RequiresLongPath bool `json:"requires_long_path,omitempty"`
}

// Meta is golden-manifest.meta.json. Note the absence of any timestamp: two runs of this program with
// the same arguments must produce identical bytes, and a timestamp would make that false.
type Meta struct {
	Harness      string `json:"harness"`
	Seed         uint64 `json:"seed"`
	Profile      string `json:"profile"`
	Count        int    `json:"count"`
	TotalBytes   int64  `json:"total_bytes"`
	CorpusRoot   string `json:"corpus_root_win"`
	VolumeSerial string `json:"volume_serial"`

	// CorpusDigest is sha256 of golden-manifest.jsonl exactly as written. "Same seed produces the same
	// corpus" is checked by comparing this one string, and every run result records it.
	CorpusDigest string `json:"corpus_digest"`

	// Faithful is false when this program could not actually apply the Windows-only properties —
	// read-only bits, alternate data streams, offline attributes. That happens when generating on a
	// non-Windows host for review. A result whose corpus was generated unfaithfully IS NOT EVIDENCE,
	// and runner/ refuses it. The flag is here rather than absent so the refusal has something to read.
	Faithful      bool     `json:"faithful"`
	FaithfulNotes []string `json:"faithful_notes,omitempty"`
	GeneratedOn   string   `json:"generated_on_goos"`

	CohortCounts map[string]int `json:"cohort_counts"`
}

