// ─────────────────────────────────────────────────────────────────────────────────────────────────
// SIZE DISTRIBUTION
//
// This is meant to look like a school laptop, not like a benchmark. A benchmark corpus is 18,000 files
// of 1 MiB and it proves almost nothing: it never exercises the 4 KiB path, never exercises a file
// bigger than a buffer, and its copy rate is suspiciously smooth. A real machine is overwhelmingly
// small documents with a handful of videos that dominate the byte count — which is exactly the shape
// that makes "kill at 43% of BYTES" land in a different place from "kill at 43% of FILES", and that
// difference is where copy tools break.
//
// `realistic` totals roughly 8.4 GB. `compact` keeps all 18,000 files and every structural case but
// shrinks the long tail to roughly 1.5 GB, for a disk-constrained host (see BLOCKED.md B1).
//
