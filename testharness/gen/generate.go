// extension choice is tied to size, because a 300 MB .txt is a thing no school laptop has ever had and
// a corpus full of them would make the copy loop look better-behaved than it is.
var extsSmall = []string{".txt", ".docx", ".odt", ".csv", ".rtf", ".url", ".lnk", ".ini"}
var extsMedium = []string{".docx", ".pdf", ".xlsx", ".jpg", ".png", ".pptx", ".heic"}
var extsLarge = []string{".pdf", ".pptx", ".jpg", ".zip", ".one", ".accdb"}
var extsHuge = []string{".mp4", ".zip", ".iso", ".mov", ".pst"}

func extFor(size int64, r *rng) string {
	switch {
	case size <= 65536:
		return r.pick(extsSmall)
	case size <= 4194304:
		return r.pick(extsMedium)
	case size <= 41943040:
		return r.pick(extsLarge)
	default:
		return r.pick(extsHuge)
	}
}

func headerFor(ext string) []byte {
	switch ext {
	case ".pdf":
		return []byte("%PDF-1.4\n%\xE2\xE3\xCF\xD3\n")
	case ".docx", ".xlsx", ".pptx", ".odt", ".zip", ".one":
		return []byte{'P', 'K', 0x03, 0x04, 0x14, 0x00, 0x06, 0x00}
	case ".jpg", ".jpeg", ".heic":
		return []byte{0xFF, 0xD8, 0xFF, 0xE0, 0x00, 0x10, 'J', 'F', 'I', 'F', 0x00}
	case ".png":
		return []byte{0x89, 'P', 'N', 'G', 0x0D, 0x0A, 0x1A, 0x0A}
	case ".mp4", ".mov":
		return []byte{0x00, 0x00, 0x00, 0x20, 'f', 't', 'y', 'p', 'i', 's', 'o', 'm'}
	case ".txt", ".csv":
		return []byte{0xEF, 0xBB, 0xBF} // UTF-8 BOM, as Notepad writes it
	default:
		return nil
	}
}

