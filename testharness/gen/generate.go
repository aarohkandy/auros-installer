// ─────────────────────────────────────────────────────────────────────────────────────────────────
// PRNG — splitmix64. Chosen because it is stateless apart from one uint64, has no warm-up, and can be
// re-implemented from these eight lines in any language if someone ever needs to audit the corpus
// without a Go toolchain.
// ─────────────────────────────────────────────────────────────────────────────────────────────────

type rng struct{ s uint64 }

func newRNG(seed uint64) *rng { return &rng{s: seed} }

func (r *rng) next() uint64 {
	r.s += 0x9E3779B97F4A7C15
	z := r.s
	z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9
	z = (z ^ (z >> 27)) * 0x94D049BB133111EB
	return z ^ (z >> 31)
}

// intn is biased for n that do not divide 2^64. The bias is under one part in 2^58 for every n used
// here and it is identical on every platform, which is the property that matters. Rejection sampling
// would remove a bias nobody can measure at the cost of a loop whose iteration count is data-dependent.
func (r *rng) intn(n int) int {
	if n <= 0 {
		return 0
	}
	return int(r.next() % uint64(n))
}

func (r *rng) int64n(n int64) int64 {
	if n <= 0 {
		return 0
	}
	return int64(r.next() % uint64(n))
}

func (r *rng) pick(xs []string) string { return xs[r.intn(len(xs))] }

// derive produces a per-file content key from (seed, label). SHA-256 rather than the PRNG stream so
// that a file's bytes depend only on its path, never on how many files were generated before it.
func derive(seed uint64, label string) uint64 {
	var b [8]byte
	binary.LittleEndian.PutUint64(b[:], seed)
	h := sha256.New()
	h.Write(b[:])
	h.Write([]byte{0})
	h.Write([]byte(label))
	sum := h.Sum(nil)
	return binary.LittleEndian.Uint64(sum[:8])
}

